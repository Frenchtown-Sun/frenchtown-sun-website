#!/usr/bin/env python3
"""Extract text blobs from a Word .docx, to put into hugo.

This is easier to work with than copy-pasting from the pdf

Docx reading generated by Gemini, output format written by hand.
"""

import argparse
import datetime
import os
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

import utils

NS = {
    "w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main",
    "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
    "mc": "http://schemas.openxmlformats.org/markup-compatibility/2006",
}


def run_to_md(run):
    """Convert a <w:r> element into text with **bold** and *italic*."""
    text = "".join(t.text or "" for t in run.findall(".//w:t", NS))
    if not text.strip():
        return text
    rPr = run.find("w:rPr", NS)
    if rPr is not None:
        is_bold = rPr.find("w:b", NS) is not None and rPr.find("w:b", NS).get(f"{{{NS['w']}}}val") != "0"
        is_ital = rPr.find("w:i", NS) is not None and rPr.find("w:i", NS).get(f"{{{NS['w']}}}val") != "0"
        # Keep leading/trailing whitespace outside the markdown markers
        lead, core, trail = re.match(r"^(\s*)(.*?)(\s*)$", text, re.DOTALL).groups()
        if is_bold:
            core = f"**{core}**"
        if is_ital:
            core = f"*{core}*"
        text = f"{lead}{core}{trail}"
    return text


def para_to_md(p, rels):
    """Convert a <w:p> paragraph into a Markdown line."""
    parts = []
    for child in p:
        tag = child.tag.split("}")[-1]
        if tag == "r":
            parts.append(run_to_md(child))
        elif tag == "hyperlink":
            rid = child.get(f"{{{NS['r']}}}id")
            url = rels.get(rid, "")
            link_text = "".join(run_to_md(r) for r in child.findall("w:r", NS)).strip()
            parts.append(f"[{link_text}]({url})" if url and link_text else link_text)

    line = "".join(parts).strip()
    if not line:
        return ""

    # Clean up adjacent bold/italic spans like **foo****bar** -> **foobar**
    line = line.replace("****", "").replace("** **", " ").replace("**", "**")

    # Detect titles by font size (Word uses half-points: 28 = 14pt)
    sizes = [int(sz.get(f"{{{NS['w']}}}val", 0)) for sz in p.findall(".//w:sz", NS)]
    if max(sizes, default=0) >= 28:
        clean_title = line.replace("**", "")
        return f"## {clean_title}"

    # Detect bullet lists
    if p.find(".//w:numPr", NS) is not None:
        return f"* {line}"

    return line


def extract_from_docx(docx_path):
    with zipfile.ZipFile(docx_path) as z:
        # Load hyperlink targets
        rels_xml = ET.fromstring(z.read("word/_rels/document.xml.rels"))
        rels = {r.get("Id"): r.get("Target") for r in rels_xml}

        # Load document and strip duplicate <mc:Fallback> & <w:pict> branches
        doc = ET.fromstring(z.read("word/document.xml"))
        for parent in doc.iter():
            for child in list(parent):
                if child.tag in (f"{{{NS['mc']}}}Fallback", f"{{{NS['w']}}}pict"):
                    parent.remove(child)

        # Print each text box (or body block) as a separated Markdown blob
        titles = []
        article_text = []
        for txbx in doc.findall(".//w:txbxContent", NS):
            lines = [para_to_md(p, rels) for p in txbx.findall("w:p", NS)]
            blob = "\n\n".join(line for line in lines if line)
            if blob and len(blob) > 1:
                if blob.startswith("#"):
                    titles.append(blob)
                else:
                    article_text.append(blob)

        return (titles, article_text)


def write_frontmatter(title, date, edition_dir):
    title = title.strip("#")
    title = title.strip()
    with open(os.path.join(edition_dir, utils.filename_from_title(title)), 'w') as wfp:
        wfp.writelines((
            '---\n'
            f'title: "{title}"\n'
            f'edition: "{date.edition}"\n'
            'weight: 0\n'
            f'date: {date.date}\n'
            'layout: "article"\n'
            '---\n'
        ))


def parse_args(args=None):
    """Parse sys.args or a passed array of args, return argparse namespace"""
    parser = argparse.ArgumentParser()

    parser.add_argument(
        '--edition',
        default=utils.next_month(),
        help='which edition to fill the frontmatter with')

    parser.add_argument(
        'docx',
        help='The docx file')

    return parser.parse_args(args)


def main(docx_path, edition):
    date = utils.parse_date(edition)
    edition_dir = utils.ensure_edition_dir(edition)
    titles, article_text = extract_from_docx(docx_path)

    utils.add_index(date, edition_dir)
    for title in titles:
        write_frontmatter(title, date, edition_dir)

    with open(os.path.join(edition_dir, "article_text.md"), 'w') as wfp:
        for text in article_text:
            wfp.writelines((
                text,
                '\n\n------------------------------------------------------\n\n'
            ))


if __name__ == "__main__":
    args = parse_args()

    main(args.docx, args.edition)
